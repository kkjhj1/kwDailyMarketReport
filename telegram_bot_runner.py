def load_dotenv_file(root_dir: Path) -> None:
    for name in (".env", ".env.txt"):
        env_path = root_dir / name
        if not env_path.exists():
            continue
        for line in env_path.read_text(encoding="utf-8-sig").splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            k, v = k.strip(), v.strip().strip("'").strip('"')
            if k and v and k not in os.environ:
                os.environ[k] = v


def resolve_default_report_url() -> str:
    """Auto-detects GitHub Pages URL when running in GitHub Actions, or uses REPORT_BASE_URL."""
    configured = os.environ.get("REPORT_BASE_URL", "").strip()
    if configured and _is_public_button_url(configured):
        return configured
    gh_repo = os.environ.get("GITHUB_REPOSITORY", "").strip()
    if "/" in gh_repo:
        owner, repo = gh_repo.split("/", 1)
        return f"https://{owner.lower()}.github.io/{repo}"
    return configured or "http://localhost:8080"


def save_dotenv_file(env_path: Path, token: str, chat_id: str, report_url: str = "http://localhost:8080") -> None:
    content = (
        f"# Auto-generated by telegram_bot_runner.py --setup\n"
        f"TELEGRAM_BOT_TOKEN={token}\n"
        f"TELEGRAM_CHAT_ID={chat_id}\n"
        f"REPORT_BASE_URL={report_url}\n"
        f"REPORT_SECRET_KEY=market-brief-secret-2026\n"
    )
    env_path.write_text(content, encoding="utf-8")


def start_background_report_server(report_dir: Path, port: int, secret_key: str) -> HTTPServer:
    report_dir.mkdir(parents=True, exist_ok=True)
    handler = create_report_handler(report_dir, secret_key, require_signature=False)
    server = HTTPServer(("0.0.0.0", port), handler)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    return server


def build_pipeline(bot_token: str, use_live_naver: bool, report_base_url: str) -> tuple[MarketBriefingPipeline, TelegramChannel]:
    fixture_provider = FixtureProvider(str(ROOT / "fixtures/market_snapshot.json"))
    if use_live_naver:
        provider = CompositeMarketDataProvider(NaverFinanceProvider(), fixture_provider)
    else:
        provider = fixture_provider

    alert_store = AlertStore(str(ROOT / "alerts.sqlite3"))
    quote_store = QuoteStore(str(ROOT / "quotes.sqlite3"))
    tg = TelegramChannel(bot_token, include_inline_button=True, use_html=True)
    gateway = DeliveryGateway(
        tg,
        primary_name="telegram",
        fallback_channel=None,
        alert_store=alert_store,
        max_retries=2,
        backoff_seconds=0.5,
    )
    pipeline = MarketBriefingPipeline(
        provider=provider,
        gateway=gateway,
        quote_store=quote_store,
        alert_store=alert_store,
        report_dir=ROOT / "reports",
        base_report_url=report_base_url,
    )
    return pipeline, tg


def interactive_setup(env_path: Path) -> tuple[str, str]:
    print("=" * 64)
    print("🤖 [텔레그램 시황 브리핑 봇] 대화형 초기 설정 마법사 (--setup)")
    print("=" * 64)
    token = input("1. @BotFather에서 발급받은 봇 토큰(HTTP API Token)을 붙여넣으세요:\n> ").strip()
    if not token:
        print("[오류] 토큰이 입력되지 않았습니다.")
        sys.exit(1)

    tg = TelegramChannel(token, include_inline_button=True, use_html=True)
    try:
        me = tg.get_me()
    except Exception as exc:
        print(f"[오류] 봇 토큰 검증에 실패했습니다: {exc}")
        sys.exit(1)

    print(f"\n✅ 봇 확인 완료: @{me.get('username')} ({me.get('first_name')})")
    print("2. 이제 텔레그램 앱에서 방금 만든 봇 대화방에 들어가 '/start' 또는 '안녕'을 전송해 주세요.")
    chats = tg.discover_chat_ids()
    while not chats:
        ans = input("   (메시지를 보낸 뒤 Enter를 누르거나, 직접 Chat ID 숫자를 입력해 주세요): ").strip()
        if ans and (ans.lstrip("-").isdigit()):
            chats = [{"chat_id": ans, "title": "직접 입력", "type": "custom", "last_text": ""}]
            break
        chats = tg.discover_chat_ids()
        if not chats:
            print("   ⚠️ 아직 봇이 수신한 메시지가 없습니다. 텔레그램에서 봇에게 먼저 말을 걸어주세요!")

    chosen_id = chats[-1]["chat_id"]
    print(f"\n✅ 수신자 Chat ID 자동 감지 성공: {chosen_id} ({chats[-1]['title']})")
    
    # 기존에 등록되어 있던 수신자 ID가 있다면 보존하고 병합합니다
    existing_ids = []
    if env_path.exists():
        for line in env_path.read_text(encoding="utf-8-sig").splitlines():
            if line.startswith("TELEGRAM_CHAT_ID="):
                raw = line.split("=", 1)[1].strip()
                existing_ids = [x.strip() for x in raw.split(",") if x.strip()]
    if chosen_id not in existing_ids:
        existing_ids.append(chosen_id)
    merged_chat_ids = ",".join(existing_ids)

    gh_url = input("3. (선택) GitHub Pages 주소를 알고 계시면 입력해 주세요 (모르시면 그냥 Enter):\n   예: https://내아이디.github.io/market-daily-briefing\n> ").strip()
    if "github.com/" in gh_url:
        parts = gh_url.split("github.com/", 1)[-1].strip("/").split("/")
        if len(parts) >= 2:
            gh_url = f"https://{parts[0].lower()}.github.io/{parts[1]}"
            print(f"   ℹ️ 저장소 주소를 GitHub Pages 주소로 자동 변환했습니다: {gh_url}")
    report_url = gh_url if gh_url else "http://localhost:8080"
    save_dotenv_file(env_path, token, merged_chat_ids, report_url)
    print(f"✅ 설정이 '{env_path.name}' 파일에 자동 저장되었습니다! (총 {len(existing_ids)}명 수신)\n")
    return token, merged_chat_ids


def main() -> int:
    env_path = ROOT / ".env"
    load_dotenv_file(ROOT)

    parser = argparse.ArgumentParser(description="Telegram Market Briefing Bot Runner (v0.4 GitHub 24/7 & Rich HTML)")
    parser.add_argument("--setup", action="store_true", help="Interactive wizard: enter token, auto-detect Chat ID, save .env, and send test")
    parser.add_argument("--token", default=os.environ.get("TELEGRAM_BOT_TOKEN", ""), help="Telegram Bot Token")
    parser.add_argument("--chat-id", default=os.environ.get("TELEGRAM_CHAT_ID", ""), help="Target Chat ID (comma-separated)")
    parser.add_argument("--discover", action="store_true", help="Verify bot token and auto-discover Chat IDs from getUpdates")
    parser.add_argument("--send-now", choices=["morning", "closing", "urgent"], help="Send a briefing immediately")
    parser.add_argument("--check-urgent", action="store_true", help="Single-pass intraday ±3%% check (ideal for GitHub Actions cron)")
    parser.add_argument("--auto-schedule", action="store_true", help="Auto-detect morning(06:30)/closing(15:40)/urgent based on current KST time (for GitHub Actions cron)")
    parser.add_argument("--live-naver", action="store_true", help="Fetch live market quotes from Naver Finance (falls back to fixture on error)")
    parser.add_argument("--attach-html", action="store_true", help="Also send the standalone .html report file directly into Telegram chat")
    parser.add_argument("--daemon", action="store_true", help="Run 24/7 scheduler + built-in web report server (port 8080) + ±3%% watch")
    parser.add_argument("--admin", action="store_true", help="Launch local FastAPI Admin Web Console (default port: 8002)")
    parser.add_argument("--port", type=int, default=8002, help="Port for built-in web server / admin console (default: 8002)")
    parser.add_argument("--report-url", default=resolve_default_report_url(), help="Base URL for detailed HTML reports (auto-detects GitHub Pages in Actions)")
    args = parser.parse_args()

    if args.setup:
        token, chat_id = interactive_setup(env_path)
        args.token = token
        args.chat_id = chat_id
        args.report_url = resolve_default_report_url()
        if not args.send_now and not args.daemon and not args.admin:
            args.send_now = "closing"
            args.live_naver = True

    if args.admin:
        from admin_server import create_admin_app, find_available_port
        import uvicorn
        target_port = args.port
        port = find_available_port(target_port)
        if port != target_port:
            print(f"⚠️ [포트 충돌 방어] 포트 {target_port}번이 이미 사용 중이어서 빈 포트 {port}번으로 자동 전환했습니다.")
        print(f"🚀 [Market Brief Admin Console] Starting server on http://localhost:{port}")
        app = create_admin_app()
        uvicorn.run(app, host="127.0.0.1", port=port)
        return 0

    if not args.token:
        print("[안내] 봇 토큰이 설정되지 않았습니다. 아래 명령어로 대화형 설정을 시작하세요:")
        print("  python telegram_bot_runner.py --setup")
        return 1

    tg_probe = TelegramChannel(args.token, include_inline_button=True, use_html=True)

    if args.discover:
        bot_info = tg_probe.get_me()
        print(f"✅ 봇 연결 성공: @{bot_info.get('username')} ({bot_info.get('first_name')})")
        chats = tg_probe.discover_chat_ids()
        if not chats:
            print("⚠️ 아직 감지된 대화방이 없습니다. 텔레그램에서 봇에게 '/start' 또는 아무 메시지나 보낸 뒤 다시 실행하세요.")
        else:
            print(f"📋 감지된 Chat ID 목록 ({len(chats)}개):")
            for c in chats:
                print(f"  - Chat ID: {c['chat_id']} | 이름: {c['title']} ({c['type']}) | 최근 메시지: {c['last_text']}")
        return 0

    recipients = [x.strip() for x in args.chat_id.split(",") if x.strip()]
    if not recipients:
        print("🔍 TELEGRAM_CHAT_ID가 비어 있어 최근 대화방 ID를 자동 조회합니다...")
        chats = tg_probe.discover_chat_ids()
        if chats:
            recipients = [chats[-1]["chat_id"]]
            print(f"✅ 자동 감지된 Chat ID({recipients[0]})로 발송을 진행합니다.")
        else:
            print("[오류] 수신자 Chat ID를 찾을 수 없습니다. 텔레그램에서 봇에게 '/start'를 보낸 뒤 다시 실행하세요.")
            return 1

    news: list[NewsItem] = []
    if args.live_naver:
        try:
            news = fetch_naver_market_news(5)
            if news:
                print(f"📰 네이버 증권 실시간 주요 시황 뉴스 {len(news)}건 수집 완료 (직링크 연결)")
        except Exception as exc:
            print(f"⚠️ 실시간 뉴스 수집 알림: {exc}")
    if not news:
        raw_news = json.loads((ROOT / "fixtures/market_news.json").read_text(encoding="utf-8"))
        news = [NewsItem(**item) for item in raw_news]

    pipeline, tg_channel = build_pipeline(args.token, args.live_naver, args.report_url)

    # Handle --auto-schedule (used by GitHub Actions cron)
    now_kst = datetime.now(KST)
    today = now_kst.date()
    cal = MarketCalendar()
    is_kr_trading = cal.is_trading_day("KR", today)

    if args.auto_schedule:
        # 1) 평일 장마감 후 (15:30 ~ 23:59 KST):
        # GitHub Actions 크론이 1~2시간 지연되어 17시, 18시에 늦게 돌더라도
        # 오늘 마감 브리핑이 아직 발송되지 않았다면 무조건 closing 1회 발송 보장!
        if is_kr_trading and (now_kst.hour > 15 or (now_kst.hour == 15 and now_kst.minute >= 30)):
            if not pipeline.alert_store.is_regular_briefing_sent("closing", today):
                print(f"⏰ [AutoSchedule] 금일({today}) 마감 브리핑 미발송 상태 감지 (실행 시각: {now_kst.strftime('%H:%M')} KST) -> 마감 브리핑 즉시 발송 진행")
                args.send_now = "closing"
            else:
                # 이미 마감 브리핑이 발송 완료된 경우, 미 야간장(22:30~)이면 긴급 감시 실행
                if now_kst.hour >= 22 or now_kst.hour < 6:
                    args.check_urgent = True
                else:
                    print(f"✅ [AutoSchedule] 금일({today}) 마감 브리핑 이미 발송 완료됨. (정규장 종료 상태)")
                    return 0
        # 2) 평일 아침 (06:30 ~ 10:00 KST):
        # 06:30 크론이 지연되어 7~8시에 돌더라도 오늘 모닝 브리핑 미발송 상태면 무조건 발송!
        elif is_kr_trading and ((now_kst.hour == 6 and now_kst.minute >= 30) or (7 <= now_kst.hour <= 10)):
            if not pipeline.alert_store.is_regular_briefing_sent("morning", today):
                print(f"⏰ [AutoSchedule] 금일({today}) 모닝 브리핑 미발송 상태 감지 (실행 시각: {now_kst.strftime('%H:%M')} KST) -> 모닝 브리핑 즉시 발송 진행")
                args.send_now = "morning"
            else:
                if now_kst.hour >= 9:
                    args.check_urgent = True
                else:
                    print(f"✅ [AutoSchedule] 금일({today}) 모닝 브리핑 이미 발송 완료됨.")
                    return 0
        # 3) 장중 (09:00 ~ 15:30 KST) 또는 미 야간장 (22:30 ~ 06:00 KST):
        else:
            args.check_urgent = True

    if args.check_urgent:
        print(f"🔍 [{now_kst.strftime('%Y-%m-%d %H:%M:%S')} KST] 장중 ±3% 급변동 감시 체크 실행...")
        quotes = pipeline.provider.fetch(DEFAULT_SYMBOLS)
        triggered = pipeline.check_and_send_urgent_alerts(quotes, recipients, now=now_kst, news=news)
        if triggered:
            for q, _, r_path in triggered:
                print(f"🚨 ±3% 급변동 알림 발송 완료: {q.symbol} -> {r_path}")
        else:
            print("✅ 현재 ±3% 돌파 자산이 없거나 금일 이미 발송 완료되었습니다.")
        return 0

    if not args.send_now and not args.daemon:
        args.send_now = "closing"
        args.live_naver = True

    if args.send_now:
        mode_label = "네이버 금융 실시간 시세(실패 시 폴백)" if args.live_naver else "오프라인 샘플 시세(Fixture)"
        print(f"🚀 [{args.send_now.upper()}] 최적화된 HTML 브리핑 생성 및 텔레그램 발송 중... (데이터: {mode_label})")
        briefing, report_path = pipeline.run_regular_briefing(
            kind=args.send_now,
            recipients=recipients,
            now=now_kst,
            news=news,
        )
        pipeline.alert_store.reserve_regular_briefing(args.send_now, today)
        print(f"✅ 텔레그램 메시지 발송 성공! (수신자 ID: {', '.join(recipients)})")
        print(f"📄 생성된 상세 HTML 리포트: {report_path}")

        # If running locally (not in GitHub Actions) or if attach_html is set,
        # also send the .html file directly so users can open it immediately from Telegram!
        is_local_run = os.environ.get("GITHUB_ACTIONS") != "true"
        if args.attach_html or is_local_run or not _is_public_button_url(args.report_url):
            for r in recipients:
                try:
                    tg_channel.send_html_Attachment(
                        r,
                        report_path,
                        caption="📊 [상세 시황 리포트 파일] 로컬에서 즉시 발송되었습니다. 터치하면 브라우저에서 대시보드가 열립니다! (GitHub 자동 발송 시 웹 링크 버튼으로 동작)",
                    )
                    print(f"📎 [{r}] 텔레그램 채팅방으로 상세 리포트(.html) 파일 직접 첨부 전송 완료!")
                except Exception as exc:
                    print(f"⚠️ HTML 파일 첨부 전송 안내: {exc}")
        return 0

    if args.daemon:
        start_background_report_server(ROOT / "reports", args.port, "market-brief-secret-2026")
        print(f"🌐 상세 웹 리포트 서버 구동 완료: http://localhost:{args.port}/reports/")
        print("⏰ 24시간 시황 브리핑 & ±3% 급변동 감시 데몬 시작...")
        cal = MarketCalendar()
        sent_regular_today: set[str] = set()
        while True:
            now = datetime.now(KST)
            today_str = now.date().isoformat()
            for kind in ("morning", "closing"):
                run_key = f"{today_str}:{kind}"
                if run_key not in sent_regular_today and cal.should_run_regular_briefing(kind, now):
                    pipeline.run_regular_briefing(kind=kind, recipients=recipients, now=now, news=news)
                    sent_regular_today.add(run_key)
                    print(f"[{now.isoformat()}] 정기 브리핑({kind}) 발송 완료")
            try:
                quotes = pipeline.provider.fetch(DEFAULT_SYMBOLS)
                triggered = pipeline.check_and_send_urgent_alerts(quotes, recipients, now=now, news=news)
                for q, _, r_path in triggered:
                    print(f"[{now.isoformat()}] 🚨 ±3% 급변동 알림 발송 완료: {q.symbol} ({r_path})")
            except Exception as exc:
                print(f"[{now.isoformat()}] 시세 감시 주기 경고: {exc}")
            time.sleep(60)

    return 0


if __name__ == "__main__":
    sys.exit(main())
