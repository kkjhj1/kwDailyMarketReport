def load_dotenv_file(root_dir: Path) -> None:
    for name in (".env", ".env.txt"):
        env_path = root_dir / name
        if not env_path.exists():
            continue
        for line in env_path.read_text(encoding="utf-8-sig").splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            k, v = k.strip(), v.strip().strip("'").strip('"')
            if k and v and k not in os.environ:
                os.environ[k] = v


def resolve_default_report_url() -> str:
    """Auto-detects GitHub Pages URL when running in GitHub Actions, or uses REPORT_BASE_URL."""
    configured = os.environ.get("REPORT_BASE_URL", "").strip()
    if configured and _is_public_button_url(configured):
        return configured
    gh_repo = os.environ.get("GITHUB_REPOSITORY", "").strip()
    if "/" in gh_repo:
        owner, repo = gh_repo.split("/", 1)
        return f"https://{owner.lower()}.github.io/{repo}"
    return configured or "http://localhost:8080"


def save_dotenv_file(env_path: Path, token: str, chat_id: str, report_url: str = "http://localhost:8080") -> None:
    content = (
        f"# Auto-generated by telegram_bot_runner.py --setup\n"
        f"TELEGRAM_BOT_TOKEN={token}\n"
        f"TELEGRAM_CHAT_ID={chat_id}\n"
        f"REPORT_BASE_URL={report_url}\n"
        f"REPORT_SECRET_KEY=market-brief-secret-2026\n"
    )
    env_path.write_text(content, encoding="utf-8")


def start_background_report_server(report_dir: Path, port: int, secret_key: str) -> HTTPServer:
    report_dir.mkdir(parents=True, exist_ok=True)
    handler = create_report_handler(report_dir, secret_key, require_signature=False)
    server = HTTPServer(("0.0.0.0", port), handler)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    return server


def build_pipeline(bot_token: str, use_live_naver: bool, report_base_url: str) -> tuple[MarketBriefingPipeline, TelegramChannel]:
    fixture_provider = FixtureProvider(str(ROOT / "fixtures/market_snapshot.json"))
    if use_live_naver:
        provider = CompositeMarketDataProvider(NaverFinanceProvider(), fixture_provider)
    else:
        provider = fixture_provider

    alert_store = AlertStore(str(ROOT / "alerts.sqlite3"))
    quote_store = QuoteStore(str(ROOT / "quotes.sqlite3"))
    tg = TelegramChannel(bot_token, include_inline_button=True, use_html=True)
    gateway = DeliveryGateway(
        tg,
        primary_name="telegram",
        fallback_channel=None,
        alert_store=alert_store,
        max_retries=2,
        backoff_seconds=0.5,
    )
    pipeline = MarketBriefingPipeline(
        provider=provider,
        gateway=gateway,
        quote_store=quote_store,
        alert_store=alert_store,
        report_dir=ROOT / "reports",
        base_report_url=report_base_url,
    )
    return pipeline, tg


